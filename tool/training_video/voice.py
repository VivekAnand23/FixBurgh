#!/usr/bin/env python3
"""Voices tool/training_video/script.json, one clip per step, with macOS text to speech, and writes how long each one lasts to
integration_test/training/durations.g.dart, so the walkthrough waits for
the narration at every step.

  python3 tool/training_video/voice.py [--voice "Ava (Premium)"] [--rate 172]

Clips go to build/training_video/voice/<id>.wav.
"""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VOICE_DIR = ROOT / 'build' / 'training_video' / 'voice'


def duration(path):
    out = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(path)],
                         check=True, capture_output=True, text=True)
    return float(out.stdout.strip())


def lines(script):
    for ch in script['chapters']:
        yield from ((sid, text) for sid, text in ch['steps'])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--voice', default='Samantha')
    ap.add_argument('--rate', type=int, default=172, help='Words per minute.')
    args = ap.parse_args()
    script = json.loads((ROOT / 'tool' / 'training_video' / 'script.json').read_text())
    VOICE_DIR.mkdir(parents=True, exist_ok=True)
    durations = {}
    for sid, text in lines(script):
        aiff, wav = VOICE_DIR / f'{sid}.aiff', VOICE_DIR / f'{sid}.wav'
        subprocess.run(['say', '-v', args.voice, '-r', str(args.rate), '-o', str(aiff), text], check=True)
        subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', str(aiff), '-ar', '48000', '-ac', '1', str(wav)], check=True)
        aiff.unlink()
        durations[sid] = round(duration(wav), 2)
    (VOICE_DIR / 'voice.json').write_text(json.dumps({'voice': args.voice, 'rate': args.rate, 'durations': durations}, indent=1))
    body = '\n'.join(f"  '{k}': {v}," for k, v in durations.items())
    (ROOT / 'integration_test' / 'training' / 'durations.g.dart').write_text(
        '// Generated by tool/training_video/voice.py; do not edit.\n'
        f'// Voice: {args.voice}, {args.rate} words a minute.\n\n'
        '/// Seconds of narration for each step of the training walkthrough.\n'
        f'const narration = <String, double>{{\n{body}\n}};\n')
    total = sum(durations.values())
    print(f'{len(durations)} clips, {total / 60:.1f} minutes of narration, voice {args.voice}')


if __name__ == '__main__':
    main()
